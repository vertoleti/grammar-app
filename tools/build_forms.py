"""Builds full inflection tables for the dictionary and the gap exercise.
Russian: generated with pymorphy3 (OpenCorpora dictionary). German: generated by rule from the deck's
principal parts (plural / 3rd person, past, perfect / comparative).
Writes vocabulary/decks/ru-forms.json and de/vocabulary/decks/de-forms.json:
  { card id: { "t": kind, "h": [column heads], "r": [[row label, cell, ...]], "x": [extra lines], "all": [every form] } }
Run: python3 tools/build_forms.py   (needs: pip install pymorphy3 pymorphy3-dicts-ru)"""
import json, re, sys


def rows(path):
    cols, out = None, []
    for l in open(path, encoding='utf-8'):
        l = l.rstrip('\n')
        if not l: continue
        if l.startswith('#'):
            if l.startswith('#columns:'): cols = l[9:].split('\t')
            continue
        f = l.split('\t'); out.append({n: (f[i] if i < len(f) else '') for i, n in enumerate(cols)})
    return out


# ---------------- Russian ----------------
def russian():
    import pymorphy3
    m = pymorphy3.MorphAnalyzer()
    CASES = [('nomn', 'Nom'), ('gent', 'Gen'), ('datv', 'Dat'), ('accs', 'Acc'), ('ablt', 'Ins'), ('loct', 'Prep')]
    out = {}

    def pick(word, pos):
        ps = [p for p in m.parse(word) if p.tag.POS in pos]
        if not ps: return None
        exact = [p for p in ps if p.normal_form == word] or ps
        return exact[0]

    def inf(p, *g):
        try:
            r = p.inflect(set(g)); return r.word if r else ''
        except Exception: return ''

    for c in rows('vocabulary/decks/ru-core.tsv') + rows('vocabulary/decks/ru-levels.tsv'):
        if c['kind'] != 'word' or not c['id']: continue
        w = c['term'].replace('́', '').strip().lower()
        if ' ' in w or ',' in w: continue
        cat = c['category']
        if cat == 'noun':
            p = pick(w, {'NOUN'})
            if not p: continue
            sg = 'Pltm' not in p.tag; pl = 'Sgtm' not in p.tag and 'Fixd' not in p.tag
            if 'Fixd' in p.tag:
                out[c['id']] = {'t': 'noun', 'h': [], 'r': [], 'x': ['Indeclinable: the same in every case.'], 'all': [w]}; continue
            h = (['Singular'] if sg else []) + (['Plural'] if pl else [])
            r = [[lab] + ([inf(p, cs, 'sing')] if sg else []) + ([inf(p, cs, 'plur')] if pl else []) for cs, lab in CASES]
            if any(not x for row in r for x in row[1:]): continue
            g = {'masc': 'masculine', 'femn': 'feminine', 'neut': 'neuter', 'ms-f': 'common gender'}.get(p.tag.gender, '')
            out[c['id']] = {'t': 'noun', 'h': h, 'r': r, 'x': [x for x in [g and g.capitalize(), 'animate' if p.tag.animacy == 'anim' else ''] if x], 'all': sorted({x for row in r for x in row[1:]})}
        elif cat == 'adjective':
            p = pick(w, {'ADJF'})
            if not p: continue
            r = []
            for cs, lab in CASES:
                if cs == 'accs':
                    mi, ma = inf(p, 'accs', 'sing', 'masc', 'inan'), inf(p, 'accs', 'sing', 'masc', 'anim')
                    pi, pa = inf(p, 'accs', 'plur', 'inan'), inf(p, 'accs', 'plur', 'anim')
                    r.append([lab, mi if mi == ma else f'{mi} / {ma}', inf(p, 'accs', 'sing', 'neut'), inf(p, 'accs', 'sing', 'femn'), pi if pi == pa else f'{pi} / {pa}'])
                else:
                    r.append([lab, inf(p, cs, 'sing', 'masc'), inf(p, cs, 'sing', 'neut'), inf(p, cs, 'sing', 'femn'), inf(p, cs, 'plur')])
            if any(not x for row in r for x in row[1:]): continue
            x = []
            short = [f.word for f in p.lexeme if f.tag.POS == 'ADJS']
            if short: x.append('Short forms: ' + ', '.join(dict.fromkeys(short)))
            comp = [f.word for f in p.lexeme if f.tag.POS == 'COMP' and 'V-ej' not in f.tag]
            if comp: x.append('Comparative: ' + comp[0])
            out[c['id']] = {'t': 'adj', 'h': ['Masc.', 'Neut.', 'Fem.', 'Plural'], 'r': r, 'x': x, 'all': sorted({y for row in r for z in row[1:] for y in z.split(' / ')} | set(short) | set(comp[:1]))}
        elif cat == 'verb':
            p = pick(w, {'INFN'})
            if not p: continue
            perf = p.tag.aspect == 'perf'
            t = 'futr' if perf else 'pres'
            pers = [('1per', 'sing', 'я'), ('2per', 'sing', 'ты'), ('3per', 'sing', 'он, она'), ('1per', 'plur', 'мы'), ('2per', 'plur', 'вы'), ('3per', 'plur', 'они')]
            pres = [inf(p, t, a, b) for a, b, _ in pers]
            past = [inf(p, 'past', 'sing', 'masc'), inf(p, 'past', 'sing', 'femn'), inf(p, 'past', 'sing', 'neut'), inf(p, 'past', 'plur')]
            if not all(pres) or not all(past): continue
            r = [[lab, f] for (_, _, lab), f in zip(pers, pres)]
            imp = [inf(p, 'impr', 'excl', 'sing'), inf(p, 'impr', 'excl', 'plur')]
            x = ['Perfective (the future is formed from these endings)' if perf else 'Imperfective',
                 f'Past: {past[0]} (he), {past[1]} (she), {past[2]} (it), {past[3]} (they)']
            if all(imp): x.append(f'Imperative: {imp[0]}, {imp[1]}')
            out[c['id']] = {'t': 'verb', 'h': ['Future' if perf else 'Present'], 'r': r, 'x': x, 'all': sorted(set(pres + past + [i for i in imp if i] + [w]))}
    return out


# ---------------- German ----------------
VOW = re.compile(r'(ei|ie|au|eu|äu|aa|ee|oo|[aeiouäöüy])', re.I)
NS = ('name', 'gedanke', 'wille', 'glaube', 'buchstabe', 'friede', 'funke', 'same')
WEAK_END = ('ent', 'ant', 'ist', 'oge', 'graf', 'nom', 'at', 'it', 'and')
WEAK_WORDS = {'nachbar', 'mensch', 'herr', 'bär', 'held', 'fürst', 'graf', 'prinz', 'bauer', 'kunde', 'junge', 'affe', 'löwe', 'hase', 'experte', 'zeuge', 'neffe', 'riese'}
NOT_WEAK = {'see', 'käse', 'staat', 'schmerz', 'professor', 'doktor', 'muskel'}


def de_noun(c):
    art = c['article']; term = c['term']
    sing = term.split(' ', 1)[1] if term.split(' ')[0] in ('der', 'die', 'das') else term
    plf = c['forms'].strip()
    pl_only = 'plural only' in (c['grammar'] or '') or c['gender'] == 'pl'
    plural = plf[4:] if plf.startswith('die ') else ''
    low = sing.lower()
    if pl_only:
        p = sing
        dat = p + 'n' if p.endswith(('e', 'er', 'el')) else p
        r = [['Nom', f'die {p}'], ['Akk', f'die {p}'], ['Dat', f'den {dat}'], ['Gen', f'der {p}']]
        return {'t': 'noun', 'h': ['Plural'], 'r': r, 'x': ['Only used in the plural.'], 'all': sorted({p, dat})}
    last = low.split('-')[-1]
    weak = art == 'der' and last not in NOT_WEAK and plural and plural in (sing + 'n', sing + 'en') and (
        low.endswith('e') or last in WEAK_WORDS or any(low.endswith(w) for w in WEAK_WORDS) or (low.endswith(WEAK_END) and len(low) > 4))
    if art == 'die':
        sg = [f'die {sing}', f'die {sing}', f'der {sing}', f'der {sing}']
    elif weak:
        n = plural   # weak nouns: every case but the nominative singular ends like the plural
        gen = (n + 's') if low.endswith(NS) else n
        sg = [f'der {sing}', f'den {n}', f'dem {n}', f'des {gen}']
    else:
        sy = len(VOW.findall(low))
        if low.endswith('nis'): g = sing + 'ses'
        elif low.endswith('bus'): g = sing + 'ses'
        elif low.endswith(('s', 'ß', 'x', 'z', 'sch')): g = sing + 'es'
        elif sy == 1 and not re.search(r'[aeiouäöüy]$', low) and low not in ('chef', 'job', 'fan', 'club'): g = sing + 'es'
        else: g = sing + 's'
        a = 'der' if art == 'der' else 'das'
        sg = [f'{a} {sing}', f'{"den" if art == "der" else "das"} {sing}', f'dem {sing}', f'des {g}']
    r = [[lab, s] for lab, s in zip(['Nom', 'Akk', 'Dat', 'Gen'], sg)]
    h = ['Singular']
    if plural:
        dp = plural + 'n' if plural.endswith(('e', 'er', 'el')) else plural
        for row, p in zip(r, [f'die {plural}', f'die {plural}', f'den {dp}', f'der {plural}']): row.append(p)
        h.append('Plural')
    x = [{'der': 'Masculine', 'die': 'Feminine', 'das': 'Neuter'}[art] + (' · n-declension: -(e)n in every case but the nominative' if weak else '')]
    if not plural: x.append('No plural in normal use.')
    return {'t': 'noun', 'h': h, 'r': r, 'x': x, 'all': sorted({w for row in r for cell in row[1:] for w in [cell.split(' ', 1)[1]]})}


PRON = ['ich', 'du', 'er/sie/es', 'wir', 'ihr', 'sie/Sie']
REFL = {'acc': ['mich', 'dich', 'sich', 'uns', 'euch', 'sich'], 'dat': ['mir', 'dir', 'sich', 'uns', 'euch', 'sich']}
DAT_REFL = {'sich anmaßen'}
IRR = {
  'sein': ['bin', 'bist', 'ist', 'sind', 'seid', 'sind'], 'haben': ['habe', 'hast', 'hat', 'haben', 'habt', 'haben'],
  'werden': ['werde', 'wirst', 'wird', 'werden', 'werdet', 'werden'], 'wissen': ['weiß', 'weißt', 'weiß', 'wissen', 'wisst', 'wissen'],
  'möchten': ['möchte', 'möchtest', 'möchte', 'möchten', 'möchtet', 'möchten'], 'können': ['kann', 'kannst', 'kann', 'können', 'könnt', 'können'],
  'müssen': ['muss', 'musst', 'muss', 'müssen', 'müsst', 'müssen'], 'dürfen': ['darf', 'darfst', 'darf', 'dürfen', 'dürft', 'dürfen'],
  'wollen': ['will', 'willst', 'will', 'wollen', 'wollt', 'wollen'], 'sollen': ['soll', 'sollst', 'soll', 'sollen', 'sollt', 'sollen'],
  'mögen': ['mag', 'magst', 'mag', 'mögen', 'mögt', 'mögen'],
}
PREPS = {'für', 'über', 'an', 'auf', 'in', 'mit', 'zu', 'von', 'nach', 'um', 'vor', 'bei', 'aus'}


def de_verb(c):
    inf0 = c['term'].strip()
    words = inf0.split()
    refl = words[0] == 'sich'
    if refl: words = words[1:]
    prep = ''
    if len(words) > 1 and words[-1] in PREPS: prep = words[-1]; words = words[:-1]
    if len(words) != 1: return None
    inf = words[0]
    parts = [p.strip() for p in c['forms'].split(',')]
    if len(parts) != 3: return None
    p3t = parts[0].split(); pt = parts[1].split(); pf = parts[2].split()
    p3 = p3t[0]; extra = [t for t in p3t[1:] if t != 'sich']
    part = extra[-1] if extra else ''
    core = inf[len(part):] if part and inf.startswith(part) else inf
    if inf in IRR: pres = IRR[inf][:]
    else:
        if core.endswith(('ern', 'eln')): stem = core[:-1]
        elif core.endswith('en'): stem = core[:-2]
        elif core.endswith('n'): stem = core[:-1]
        else: return None
        ich = stem + 'e'
        if p3.endswith('st') or re.search(r'[sßxz]t$', p3) and not p3.endswith('tet'):
            du = p3 if p3.endswith(('st', 'ßt', 'xt', 'zt')) else p3[:-1] + 'st'
        elif stem.endswith(('t', 'd')) and p3 != stem + 'et':
            du = p3 + 'st'
        else:
            du = p3[:-1] + 'st'
        ihr = stem + ('et' if stem.endswith(('t', 'd')) or re.search(r'[^aeiouäöülrh][mn]$', stem) else 't')
        pres = [ich, du, p3, core, ihr, core]
    pv = pt[0]
    if pv in ('–', '-'): past = None
    elif pv.endswith('te'):
        past = [pv, pv + 'st', pv, pv + 'n', pv + 't', pv + 'n']
    else:
        wir = pv + ('n' if pv.endswith('e') else 'en')
        past = [pv, pv + ('est' if pv.endswith(('s', 'ß', 'z')) else 'est' if pv.endswith(('t', 'd')) else 'st'), pv, wir, pv + ('et' if pv.endswith(('t', 'd')) else 't'), wir]
        if pv == 'war': past[1] = 'warst'
    aux = pf[0] if pf and pf[0] in ('hat', 'ist') else ''
    pp = pf[-1] if aux else ''
    AUX = {'hat': IRR['haben'], 'ist': IRR['sein']}
    R = REFL['dat' if ('sich ' + inf) in DAT_REFL else 'acc']

    def say(i, v, tail=''):
        bits = [PRON[i].split('/')[0] if i != 5 else 'sie', v]
        if refl: bits.append(R[i])
        if tail: bits.append(tail)
        return ' '.join(bits)
    tab = []
    for i in range(6):
        row = ['', say(i, pres[i], part)]
        if past: row.append(say(i, past[i], part))
        if aux: row.append(say(i, AUX[aux][i], pp))
        tab.append(row)
    h = ['Präsens'] + (['Präteritum'] if past else []) + (['Perfekt'] if aux else [])
    x = []
    if part: x.append(f'Separable: the prefix “{part}” goes to the end in a main clause.')
    if refl: x.append('Reflexive: ' + ('dative pronoun (mir, dir…)' if R is REFL['dat'] else 'accusative pronoun (mich, dich…)') + '.')
    if prep: x.append(f'Used with “{prep}”.')
    if aux == 'ist': x.append('Perfect with sein.')
    allf = set(pres + (past or []) + [pp, inf, core]) | ({part + f for f in pres + (past or [])} if part else set())
    return {'t': 'verb', 'h': h, 'r': tab, 'x': x, 'all': sorted(f for f in allf if f)}


def de_adj(c):
    f = [p.strip() for p in c['forms'].split(',') if p.strip()]
    if len(f) != 2: return None
    base = c['term'].strip()
    comp, sup = f
    st = sup[3:] if sup.startswith('am ') else sup
    stem_sup = st[:-2] if st.endswith('en') else st
    r = [['Positive', base], ['Comparative', comp], ['Superlative', sup]]
    x = [f'Before a noun: ein {base}er Tag, der {base}e Tag · ein {comp}er Tag · der {stem_sup}e Tag']
    if base.endswith('el'):
        x = [f'Before a noun the -e- drops: ein {base[:-2]}ler …']
    if base.endswith('er') and len(base) > 4 and base in ('teuer', 'sauer'):
        x = [f'Before a noun the -e- drops: ein {base[:-2]}rer …']
    allf = {base, comp, st, stem_sup + 'e'}
    for e in ('e', 'en', 'er', 'es', 'em'):
        b = base[:-2] + base[-1] if base in ('teuer', 'sauer') else base
        allf |= {b + e, comp + e, stem_sup + e}
    return {'t': 'adj', 'h': [''], 'r': r, 'x': x, 'all': sorted(allf)}


def german():
    out = {}
    for c in rows('de/vocabulary/decks/de-core.tsv'):
        if c['kind'] != 'word': continue
        r = None
        if c['category'] == 'noun': r = de_noun(c)
        elif c['category'] == 'verb': r = de_verb(c)
        elif c['category'] == 'adjective': r = de_adj(c)
        if r: out[c['id']] = r
    return out


if __name__ == '__main__':
    de = german()
    json.dump(de, open('de/vocabulary/decks/de-forms.json', 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    print('German tables:', len(de))
    try:
        ru = russian()
        json.dump(ru, open('vocabulary/decks/ru-forms.json', 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
        print('Russian tables:', len(ru))
    except ImportError:
        print('pymorphy3 not installed: Russian tables not rebuilt', file=sys.stderr)
