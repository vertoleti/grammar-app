"""Builds the search index of the grammar guides: shared/search-ru.js and shared/search-de.js.
Each section: id, title, chapter, a short snippet and its plain text for matching.
Run after editing guide/*.txt: python3 tools/build_search.py"""
import glob, json, re

HEAD = re.compile(r'^(#{1,3})\s+(.*?)\s*\{#([\w-]+)\}\s*$')


def plain(s):
    s = re.sub(r'\[([^\]]+)\]\(#[\w-]+\)', r'\1', s)
    s = re.sub(r'[*_`>|!]+', ' ', s)
    s = re.sub(r'^@for .*$', '', s, flags=re.M)
    s = re.sub(r'^-\s+', '', s, flags=re.M)
    return re.sub(r'\s+', ' ', s).strip()


def build(code):
    out, chapter, cur, buf = [], '', None, []

    def flush():
        if cur:
            text = plain('\n'.join(buf))
            out.append({'id': cur[1], 't': cur[0], 'c': chapter if chapter != cur[0] else '', 's': text[:150], 'x': text[:900]})
    for f in sorted(glob.glob(f'guide/{code}/*.txt')):
        for line in open(f, encoding='utf-8'):
            m = HEAD.match(line.rstrip('\n'))
            if m:
                flush(); buf = []
                lvl, title, sid = len(m.group(1)), m.group(2), m.group(3)
                if lvl == 1: chapter = title
                cur = (title, sid)
            else:
                buf.append(line.rstrip('\n'))
    flush()
    js = f'/* Generated by tools/build_search.py from guide/{code}/*.txt */\nwindow.SEARCH_GUIDE = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
    open(f'shared/search-{code}.js', 'w', encoding='utf-8').write(js)
    print(code, 'guide sections indexed:', len(out), '| bytes:', len(js.encode()))


if __name__ == '__main__':
    build('ru'); build('de')
